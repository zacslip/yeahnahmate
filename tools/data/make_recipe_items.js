// Builds YeahNahMate/Data/RecipeItems.lua: recipe spell ID -> the item it makes, for the 12
// professions the addon knows. Read from WoW Forever's own game files (SkillLineAbility + SpellEffect)
// with wow.export's readers, offline. Re-run after a game patch that adds recipes.
// Use: WOWEXPORT=<a wow.export checkout> [WOW=<the World of Warcraft folder>] node tools/data/make_recipe_items.js
// (WOW defaults to the Battle.net install folder.)
const path = require('path');
const fs = require('fs');
const Module = require('module');

const WE = process.env.WOWEXPORT;
if (!WE) { console.error('Set WOWEXPORT to a wow.export checkout (https://github.com/Kruithne/wow.export).'); process.exit(1); }
const WOW = process.env.WOW || 'C:/Program Files (x86)/World of Warcraft';
const OUT = path.join(__dirname, '..', '..', 'YeahNahMate', 'Data', 'RecipeItems.lua');
const LINES = { 171: 'Alchemy', 164: 'Blacksmithing', 185: 'Cooking', 333: 'Enchanting', 202: 'Engineering',
	129: 'First Aid', 356: 'Fishing', 182: 'Herbalism', 165: 'Leatherworking', 186: 'Mining', 393: 'Skinning', 197: 'Tailoring' };
const CREATE_ITEM = 24;

globalThis.BUILD_RELEASE = false;
globalThis.requestAnimationFrame = f => setTimeout(f, 0);
globalThis.nw = { __dirname: WE + '/src', App: { dataPath: process.env.LOCALAPPDATA + '/wow.export/User Data/Default', manifest: { version: '0.0.0' } } };
const resolve = Module._resolveFilename;
Module._resolveFilename = function (req, ...rest) {
	if (/mmap\.node$/.test(req))
		return WE + '/node_addons/mmap/build/Release/mmap.node';
	return resolve.call(this, req, ...rest);
};

(async () => {
	const core = require(WE + '/src/js/core');
	const strip = s => s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '');
	const config = JSON.parse(strip(fs.readFileSync(WE + '/src/default_config.jsonc', 'utf8')));
	try { Object.assign(config, JSON.parse(fs.readFileSync(nw.App.dataPath + '/config.json', 'utf8'))); } catch (e) {}
	core.view = Object.assign(core.makeNewView(), { config, $watch: (k, f, o) => { if (o && o.immediate) f(config.cascLocale); return () => {}; } });
	const CASCLocal = require(WE + '/src/js/casc/casc-source-local');
	const WDCReader = require(WE + '/src/js/db/WDCReader');
	const casc = new CASCLocal(WOW);
	await casc.init();
	const pick = casc.builds.findIndex(b => b.Product === 'wowf');      // WoW Forever
	if (pick < 0) throw new Error('no wowf build in ' + casc.builds.map(b => b.Product).join(', '));
	console.log('build', casc.builds[pick].Product, casc.builds[pick].Version);
	await casc.load(pick);
	core.view.casc = casc;

	const read = async name => { const r = new WDCReader('DBFilesClient/' + name + '.db2'); await r.parse(); return r.getAllRows(); };
	const sla = await read('SkillLineAbility');
	const spells = new Map();               // spell -> line
	for (const [, r] of sla) if (LINES[r.SkillLine]) spells.set(r.Spell, r.SkillLine);
	const eff = await read('SpellEffect');
	const items = new Map();
	for (const [, r] of eff) {
		if (r.Effect === CREATE_ITEM && spells.has(r.SpellID)) {
			const item = Array.isArray(r.EffectItemType) ? r.EffectItemType[0] : r.EffectItemType;
			if (item > 0 && !items.has(r.SpellID)) items.set(r.SpellID, item);
		}
	}
	const ids = [...items.keys()].sort((a, b) => a - b);
	let lua = '-- Generated by tools/data/make_recipe_items.js from WoW Forever\'s game files. Do not edit.\n'
		+ '-- Recipe spell ID -> the item it makes (' + ids.length + ' recipes). Enchants make no item.\n'
		+ 'local ADDON, ns = ...\nns.RecipeItem = {\n';
	let line = '';
	for (const id of ids) {
		const part = '[' + id + ']=' + items.get(id) + ',';
		if (line.length + part.length > 110) { lua += line + '\n'; line = ''; }
		line += part;
	}
	lua += line + '\n}\n';
	fs.mkdirSync(path.dirname(OUT), { recursive: true });
	fs.writeFileSync(OUT, lua);
	const perLine = {};
	for (const id of ids) perLine[LINES[spells.get(id)]] = (perLine[LINES[spells.get(id)]] || 0) + 1;
	console.log('spells in professions:', spells.size, 'making items:', ids.length, perLine);
	console.log('wrote', OUT, fs.statSync(OUT).size, 'bytes');
	process.exit(0);
})().catch(e => { console.error(e); process.exit(1); });
